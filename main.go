// git-regret — prove your hacks were regrets. Go edition.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/Arch087146/git-regret/internal/regret"
	"github.com/Arch087146/git-regret/internal/ui"
)

const version = "1.0.0"

// valueFlags take an argument; everything else is boolean or positional.
var valueFlags = map[string]bool{"--author": true, "--since": true, "--md": true, "--model": true, "--dir": true}

// positional holds non-flag arguments extracted before flag.Parse, because
// Go's flag package stops at the first positional argument.
var positional []string

func extractPositionals() {
	args := os.Args[1:]
	var rest []string
	for i := 0; i < len(args); i++ {
		a := args[i]
		if strings.HasPrefix(a, "-") && a != "-" {
			rest = append(rest, a)
			if valueFlags[a] && i+1 < len(args) && !strings.HasPrefix(args[i+1], "-") {
				rest = append(rest, args[i+1])
				i++
			}
			continue
		}
		positional = append(positional, a)
	}
	os.Args = append([]string{os.Args[0]}, rest...)
}

func main() {
	extractPositionals()
	author := flag.String("author", "", "only judge one sinner")
	since := flag.String("since", "", "only recent sins, e.g. \"1 year ago\"")
	jsonOut := flag.Bool("json", false, "machine-readable shame")
	md := flag.String("md", "", "write markdown report to file")
	flag.Usage = usage
	flag.Parse()

	root, _ := os.Getwd()
	if len(positional) > 0 {
		root = positional[0]
	}
	root, _ = filepath.Abs(root)

	commits, err := regret.LoadHistory(root, *author, *since)
	if err != nil {
		fmt.Fprintln(os.Stderr, "✗", err)
		os.Exit(1)
	}

	// interactive: no flags, real terminal
	if !*jsonOut && *md == "" && *author == "" && *since == "" && len(positional) == 0 && isTTY() {
		ui.Run(root)
		return
	}

	regret.LinkRegrets(commits, 90)
	r := regret.Score(commits)

	if *jsonOut {
		json.NewEncoder(os.Stdout).Encode(r)
	} else {
		fmt.Print(render(r))
	}

	if *md != "" {
		os.WriteFile(*md, []byte(markdown(r, filepath.Base(root))), 0o644)
	}
}

func render(r regret.Report) string {
	var b strings.Builder
	fmt.Fprintf(&b, "\n🔥 JUDGING · REGRET INDEX %d/100 · Grade %s\n%s\n\n", r.Score, r.Grade, r.Verdict)
	b.WriteString(regret.Bar("Regret rate (hacks undone)", r.RegretRate, fmt.Sprintf("%d/%d hacks undone", r.Proven, r.Suspects)))
	b.WriteString("\n")
	b.WriteString(regret.Bar("Late-night commits", pctOf(r.LateNight, r.Total), fmt.Sprintf("%d/%d commits", r.LateNight, r.Total)))
	b.WriteString("\n")
	b.WriteString(regret.Bar("Weekend commits", pctOf(r.Weekend, r.Total), fmt.Sprintf("%d/%d commits", r.Weekend, r.Total)))
	b.WriteString("\n")
	if len(r.Hall) == 0 {
		fmt.Fprintln(&b, "\n✔ No proven regrets found. Either you're careful or you're lucky. Usually lucky.")
	} else {
		fmt.Fprintf(&b, "\nHALL OF SHAME (%d proven regrets)\n\n", len(r.Hall))
		for _, s := range r.Hall {
			fmt.Fprintf(&b, "✗ %s %s\n   undone %d days later by %s: %q\n", s.Hash, s.Msg, s.DaysLater, s.UndoneBy, s.UndoneMsg)
		}
	}
	b.WriteString("\n")
	return b.String()
}

func pctOf(part, whole int) float64 {
	if whole == 0 {
		return 0
	}
	return float64(part) / float64(whole)
}

func markdown(r regret.Report, name string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# 🔥 Regret report for %q\n\n", name)
	fmt.Fprintf(&b, "> Regret Index: **%d/100** · Grade **%s** — %s\n\n", r.Score, r.Grade, r.Verdict)
	fmt.Fprintf(&b, "%d commits · %d suspects · %d proven regrets\n\n", r.Total, r.Suspects, r.Proven)
	for _, s := range r.Hall {
		fmt.Fprintf(&b, "- `%s` **%s**\n  — undone %d days later by `%s`: %q\n", s.Hash, s.Msg, s.DaysLater, s.UndoneBy, s.UndoneMsg)
	}
	b.WriteString("\n<sub>generated by git-regret (Go edition)</sub>\n")
	return b.String()
}

func isTTY() bool {
	fi, err := os.Stdout.Stat()
	if err != nil {
		return false
	}
	return fi.Mode()&os.ModeCharDevice != 0
}

func usage() {
	fmt.Print(`git-regret — prove your hacks were regrets (Go edition)

Usage: git-regret [dir] [flags]

Run with no flags in a terminal → interactive TUI.

  --author <name>   only judge one sinner
  --since <date>    only recent sins
  --json            machine-readable shame
  --md <file>       write markdown report to file
`)
}
